class Spy:
    """Wraps a provider and records everything sent to it."""

    def __init__(self, llm):
        self._llm, self.sent = llm, []
        self.name, self.model = llm.name, llm.model

    async def complete_json(self, system, user, max_tokens=1200):
        self.sent.append(system + "\n" + user)
        return await self._llm.complete_json(system, user, max_tokens)


def view(r):
    return sorted((f.secret_type, f.resource, f.severity) for f in r.findings)


async def main(providers, out):
    with tempfile.TemporaryDirectory() as d:
        for name, text in FAKE.items():
            p = Path(d) / name
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
        base = await scan_directory(d, make_llm("none"))
        rows = []
        for prov in providers:
            spy = Spy(make_llm(prov))
            r = await scan_directory(d, spy, Budget())
            fps = {f.fingerprint for f in r.findings}
            leaked = (
                [s for s in SECRETS if any(s in x for x in spy.sent)]
                + [f for f in fps if any(f in x for x in spy.sent)]
                + [f.preview for f in r.findings if any(f.preview in x for x in spy.sent)]
            )
            notes = [f.note for f in r.findings if f.note]
            dirty = [n for n in notes if detectors.scan_text(n) or "http" in n]
            rows.append(
                {
                    "provider": f"{r.provider}/{r.model}",
                    "stable": view(r) == view(base),
                    "no_secret_sent": not leaked,
                    "clean": not dirty,
                    "notes": len(notes),
                    "rejected": len(r.dropped),
                    "calls": len(spy.sent),
                    "cost": sum(s.cost_usd for s in r.trace),
                    "ms": r.duration_ms,
                }
            )
            print(rows[-1], flush=True)
    bad = sum(not (x["stable"] and x["no_secret_sent"] and x["clean"]) for x in rows)
    c = lambda b: "✓" if b else "✗"  # noqa: E731
    L = [
        "# Evaluation results",
        "",
        f"{len(base.findings)} fake findings in {base.sources[0].scanned} files (plus a benign README with placeholders). Generated by `evals/run.py`.",
        "",
        "| provider | findings stable | no secret sent to the model | clean notes | notes kept | rejected | model calls | cost | ms |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    L += [
        f"| {x['provider']} | {c(x['stable'])} | {c(x['no_secret_sent'])} | {c(x['clean'])} | {x['notes']} | {x['rejected']} | {x['calls']} | ${x['cost']:.4f} | {x['ms']} |"
        for x in rows
    ]
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out}; violations: {bad}")
    return 1 if bad else 0


